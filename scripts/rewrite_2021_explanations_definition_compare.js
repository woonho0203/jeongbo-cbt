function clean(text = '') {
  return String(text)
    .replace(/\s+/g, ' ')
    .replace(/\s+([,.])/g, '$1')
    .trim();
}

function answerText(q) {
  const index = Number(q.answer) - 1;
  return Array.isArray(q.options) && q.options[index] ? clean(q.options[index]) : '';
}

function isNegative(stem = '') {
  return /(틀린 것은|옳지 않은 것은|아닌 것은|해당하지 않는|거리가 먼 것은|볼 수 없는|없는 것은|적절하지 않은|고려하지 않아도 되는|지원.*없는|속하지 않는)/.test(stem);
}

function isSql(q) {
  const text = `${q.stem || ''} ${(q.options || []).join(' ')}`;
  return /\b(SELECT|FROM|WHERE|JOIN|GROUP\s+BY|HAVING|ORDER\s+BY|ALTER|DDL|DML|DCL|CREATE|DELETE|INSERT|UPDATE)\b/i.test(text);
}

function isCode(q) {
  const stem = q.stem || '';
  const text = `${stem} ${(q.options || []).join(' ')}`;
  return /(C언어|JAVA|Java|파이썬|Python|출력문|출력 결과|실행 결과|printf|System\.out|while\s*\(|for\s*\(|print\(|포인터)/i.test(text) && !isSql(q);
}

function isCalc(q) {
  const text = `${q.stem || ''} ${(q.options || []).join(' ')}`;
  const calcPattern = /(계산|얼마|라인수|LOC|생산성|개월|\d+\s*K\b|비트|전송률|페이지|스케줄링|평균|fan-in|fan-out|카디널리티|차수|튜플의 최대|주소|임계경로|CPM|해밍|패리티|서브넷|마스크)/i;
  const passPattern = /PASS\s*\d|PASS\s+[0-9]/;
  if (isNegative(q.stem || '') && !calcPattern.test(text) && !passPattern.test(text)) {
    return false;
  }
  return calcPattern.test(text) || passPattern.test(text);
}

