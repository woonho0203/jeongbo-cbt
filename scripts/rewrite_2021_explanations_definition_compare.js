function concept(text, q, allowStem = false) {
  const target = clean(text);
  for (const [pattern, desc] of conceptRules) {
    if (pattern.test(target)) return desc;
  }
  if (allowStem) {
    for (const [pattern, desc] of conceptRules) {
      if (pattern.test(q.stem || '')) return desc;
    }
  }
  if (/^\d/.test(target) || /:/.test(target)) return `${target}는 문제의 계산 조건을 적용해 얻어야 하는 결과 후보임`;
  if (target.length > 55) return `${target}는 보기 문장 자체의 개념 관계와 사실 여부를 판단해야 하는 설명임`;
  return `${target}는 문제 단서와 비교해야 하는 핵심 선택지 개념임`;
}

function stemClue(q) {
  const stem = clean(q.stem || '');
  const quoted = stem.match(/['"“‘]([^'"”’]{2,80})['"”’]/);
  if (quoted) return quoted[1];
  return stem
    .replace(/^(다음|아래)\s*/, '')
    .replace(/(으로|에 대한|에 관한|에 해당하는|에 해당되지 않는|중|는\?|은\?).*$/, '')
    .slice(0, 90);
}

function optionLine(q, option, idx, negative) {
  const num = idx + 1;
  const text = clean(option);
  const def = concept(text, q, false);
  if (num === Number(q.answer)) {
    if (negative) {
      return `  - ${num}번 ${text}: ${def} 보기의 표현이 실제 개념과 다르거나 문제 범주에 포함되지 않으므로 부정형 문제의 정답 조건에 해당함.`;
    }
    return `  - ${num}번 ${text}: ${def} 문제 단서와 직접 일치하므로 정답 조건에 해당함.`;
  }
  if (negative) {
    return `  - ${num}번 ${text}: ${def} 정답 보기와 달리 문제에서 묻는 범주에 포함되거나 올바른 설명이므로 제외함.`;
  }
  return `  - ${num}번 ${text}: ${def} 문제 단서가 요구하는 핵심 역할과 다르므로 정답 조건에 해당하지 않음.`;
}

function answerOptionLine(q, negative) {
  const ans = answerText(q);
  const def = concept(ans, q, true);
  if (negative) {
    return `- 정답 보기: ${ans}임. ${def} 보기의 표현이 실제 개념, 분류, 역할과 어긋나므로 부정형 문제의 정답 조건에 해당함.`;
  }
  return `- 정답 보기: ${ans}임. ${def} 문제 단서와 직접 일치하므로 정답 조건에 해당함.`;
}

function wrongOptionLines(q, negative) {
  return (q.options || [])
    .map((option, index) => ({ option, index }))
    .filter(({ index }) => index + 1 !== Number(q.answer))
    .map(({ option, index }) => optionLine(q, option, index, negative));
}

