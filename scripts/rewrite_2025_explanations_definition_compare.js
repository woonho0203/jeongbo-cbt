      '  - 과정 2: 3이 8보다 작으므로 8을 뒤로 밀고 3을 첫 위치에 삽입함.',
      '  - 과정 3: 나머지 원소 4, 9, 7은 아직 처리하지 않아 결과는 3, 8, 4, 9, 7임.',
